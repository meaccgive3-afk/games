export const PLAYER_MAP: Record<string, Player> = Object.fromEntries(PLAYERS.map((p) => [p.id, p]))

export function getPlayer(id: string | undefined | null): Player | null {
  if (!id) return null
  return PLAYER_MAP[id] ?? null
}

export function playersByGroup(group: PositionGroup) {
  return PLAYERS.filter((p) => p.group === group)
}
